/** A table cell: one line, backslashes then pipes escaped (a "\|" in the text can't unescape a pipe). */
const cell = (s: string) => s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n+/g, "<br>").trim() || "—";
const table = (head: string[], rows: string[][]) =>
  [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");

export function render(a: Assessment, lang: Language, configName = "law25.config.mjs"): string {
  if (!languagesOf(a).includes(lang)) throw new Error(`the assessment's languages don't include ${lang}`);
  const l = L[lang];
  const t = (x: Text | undefined) => textIn(x, lang);
  const day = (iso: string) => l.date.format(new Date(`${iso}T00:00:00Z`));
  const colon = lang === "fr" ? `${NB}:` : ":";
  const data = a.data ?? [];
  const providers = a.providers ?? [];
  const risks = a.risks ?? [];
  const sensitive = data.filter((d) => d.sensitive && t(d.sensitive).trim());
  const outside = providers.filter((p) => p.outsideQuebec);
  const done = risks.filter((r) => r.status === "done").length;
  const out: string[] = [];

  out.push(`# ${l.title(t(a.project.name))}`, "");
  out.push(table(["", ""], [
    [l.organisation, t(a.organisation.name)],
    [l.officer, `${t(a.organisation.privacyOfficer.title)}, ${t(a.organisation.privacyOfficer.contact)}`],
    [l.system, t(a.project.name)],
    [l.assessed, day(a.assessed)],
    [l.nextReview, day(a.nextReview)],
    ...(a.officerConsulted ? [[l.consulted, day(a.officerConsulted)]] : []),
    [l.basis, l.basisText],
  ]).replace(/^\| {2}\| {2}\|$/m, "| | |"), "");
  out.push(`*${l.disclaimer}*`, "");

  out.push(`## ${l.summary}`, "");
  out.push(`- ${l.sumData(data.length, sensitive.length)}`, `- ${l.sumProviders(providers.length, outside.length)}`, `- ${l.sumRisks(risks.length, done)}`, "");

  out.push(`## 1. ${l.project}`, "", t(a.project.description), "");
  out.push(`### ${l.objectives}`, "", ...a.project.objectives.map((o) => `- ${t(o)}`), "");
  out.push(`### ${l.proportionality}`, "", t(a.project.proportionality), "");
  if (a.portability) out.push(`### ${l.portability}`, "", t(a.portability), "");

  out.push(`## 2. ${l.roles}`, "");
  out.push(a.roles?.length ? table([l.who, l.role], a.roles.map((r) => [t(r.who), t(r.role)])) : l.noneRecorded, "");
  if (a.consultations?.length) out.push(`### ${l.consultations}`, "", ...a.consultations.map((c) => `- ${t(c)}`), "");

  out.push(`## 3. ${l.information}`, "");
  out.push(table(l.cols, data.map((d) => [
    t(d.name), t(d.whose), l.source[d.source] ?? d.source, t(d.purpose), t(d.retention), t(d.storedIn), t(d.access),
    (d.fields ?? []).map((f) => `\`${f}\``).join(", "),
  ])), "");

  out.push(`## 4. ${l.sensitive}`, "", l.sensitiveIntro, "");
  out.push(sensitive.length ? sensitive.map((d) => `- **${t(d.name)}**${colon} ${t(d.sensitive)}`).join("\n") : l.noSensitive, "");

  out.push(`## 5. ${l.providers}`, "");
  if (!providers.length) out.push(l.noProviders, "");
  else {
    // A provider names its data in any language; the report names it in its own.
    const named = (n: string) => t(data.find((d) => allValues(d.name).includes(n))?.name) || n;
    out.push(table(l.providerCols, providers.map((p) => [t(p.name), t(p.service), p.data.map(named).join(", "), t(p.location), p.outsideQuebec ? l.yes : l.no, t(p.safeguards)])), "");
    if (outside.length) {
      out.push(l.transferIntro, "");
      for (const p of outside) {
        out.push(`### ${t(p.name)}`, "");
        for (const k of ["sensitivity", "purposes", "protection", "legalFramework", "conclusion"] as const) out.push(`- **${l.factors[k]}**${colon} ${t(p.transfer?.[k])}`);
        out.push("");
      }
    }
  }

  out.push(`## 6. ${l.risks}`, "");
  for (const stage of ["collection", "use", "communication", "retention", "other"] as const) {
    const here = risks.filter((r) => r.stage === stage);
    if (!here.length) continue;
    out.push(`### ${l.stage[stage]}`, "", table(l.riskCols, here.map((r) => [t(r.risk), t(r.measure), l.status[r.status]])), "");
  }

  out.push(`## 7. ${l.plan}`, "");
  const open: Risk[] = risks.filter((r) => r.status !== "done").sort((x, y) => (x.due ?? "9999").localeCompare(y.due ?? "9999"));
  out.push(open.length ? table(l.planCols, open.map((r) => [t(r.measure), t(r.owner), r.due ? day(r.due) : "", l.status[r.status]])) : l.planDone, "");

  out.push(`## 8. ${l.approval}`, "");
  out.push(a.approvals?.length ? table(l.approvalCols, a.approvals.map((x) => [t(x.by), t(x.title), day(x.date)])) : l.notApproved, "");
  if (a.updates?.length) {
    out.push(`### ${l.history}`, "", ...[...a.updates].sort((x, y) => y.date.localeCompare(x.date)).map((u) => `- ${day(u.date)}${colon} ${t(u.summary)}`));
  }
  out.push("", "---", "", l.footer(configName), "");
  return out.join("\n");
}
